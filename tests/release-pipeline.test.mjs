import test from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync, sign, verify } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mkdtemp, mkdir, symlink, writeFile, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const version = '2.2.0';
const catalog = await import('../scripts/release-catalog.mjs').catch(() => ({}));
const signing = await import('../scripts/sign-updates.mjs').catch(() => ({}));
async function fixture(t) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'putio-release-test-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  for (const name of catalog.releaseAssetNames(version, 'build')) await writeFile(path.join(directory, name), `generated fixture ${name}`);
  return directory;
}
test('the exact catalog keeps all six portable downloads and both installer architectures', () => {
  assert.equal(typeof catalog.releaseAssetNames, 'function');
  const build = catalog.releaseAssetNames(version, 'build');
  assert.equal(build.length, 17);
  assert.ok(build.includes('PutioManager-2.2.0-windows-arm64-setup.exe'));
  assert.ok(build.includes('PutioManager-2.2.0-windows-x64-setup.msi'));
  assert.ok(build.includes('PutioManager-2.2.0-macos-arm64-update.zip'));
  assert.ok(build.includes('PutioManager-WiX-6.0.2-source.tar.gz'));
  assert.equal(catalog.releaseAssetNames(version, 'published').length, 21);
  assert.throws(() => catalog.releaseAssetNames('2.2.0-rc.1'), /version/i);
  assert.throws(() => catalog.releaseAssetNames('2.2.70000'), /version/i);
});
test('inventory rejects extra and missing release assets', async t => {
  const directory = await fixture(t);
  assert.equal((await catalog.inspectReleaseAssets(directory, version)).length, 17);
  await writeFile(path.join(directory, 'unreviewed.exe'), 'fixture');
  await assert.rejects(catalog.inspectReleaseAssets(directory, version), /inventory/i);
  await rm(path.join(directory, 'unreviewed.exe'));
  await rm(path.join(directory, catalog.releaseAssetNames(version)[0]));
  await assert.rejects(catalog.inspectReleaseAssets(directory, version), /inventory/i);
});
test('the asset catalog rejects directory payloads and symbolic links', async t => {
  const directory = await fixture(t), name = catalog.releaseAssetNames(version)[0], filename = path.join(directory, name);
  await rm(filename); await mkdir(filename);
  await assert.rejects(catalog.inspectReleaseAssets(directory, version), /file/i);
  await rm(filename, { recursive: true });
  const target = path.join(directory, catalog.releaseAssetNames(version)[1]);
  try { await symlink(target, filename, 'file'); }
  catch (error) { if (error.code === 'EPERM') { t.diagnostic('File symlink creation requires Windows developer privileges; directory rejection was verified.'); return; } throw error; }
  await assert.rejects(catalog.inspectReleaseAssets(directory, version), /file/i);
});
test('streaming inventory detects mutation with exact content hashes', async t => {
  const directory = await fixture(t);
  const before = await catalog.inspectReleaseAssets(directory, version);
  await writeFile(path.join(directory, before[0].name), 'changed generated bytes');
  const after = await catalog.inspectReleaseAssets(directory, version);
  assert.notEqual(after[0].sha256, before[0].sha256);
  assert.equal(after[0].bytes, 23);
});
test('publication signs canonical exact metadata and both raw Mac archives', async t => {
  const directory = await fixture(t);
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const result = await signing.signUpdates(directory, version, privateKey, publicKey);
  const bytes = await readFile(path.join(directory, result.manifest));
  const sig = await readFile(path.join(directory, result.signature), 'utf8');
  assert.ok(verify(null, bytes, publicKey, Buffer.from(sig.trim(), 'base64')));
  const manifest = JSON.parse(bytes);
  assert.deepEqual(Object.keys(manifest), ['schema', 'version', 'assets']);
  assert.equal(manifest.schema, 1);
  assert.equal(manifest.assets.length, 19);
  assert.deepEqual(manifest.assets.map(asset => asset.name), manifest.assets.map(asset => asset.name).sort());
  for (const arch of ['x64', 'arm64']) {
    const appcast = await readFile(path.join(directory, `appcast-${arch}.xml`), 'utf8');
    const raw = await readFile(path.join(directory, `PutioManager-${version}-macos-${arch}-update.zip`));
    const archiveSignature = /sparkle:edSignature="([A-Za-z0-9+/=]+)"/.exec(appcast)?.[1];
    assert.ok(archiveSignature);
    assert.equal(manifest.assets.find(asset => asset.name === `PutioManager-${version}-macos-${arch}-update.zip`).ed25519, archiveSignature);
    assert.ok(verify(null, raw, publicKey, Buffer.from(archiveSignature, 'base64')));
    assert.match(appcast, /<sparkle:minimumSystemVersion>13\.0<\/sparkle:minimumSystemVersion>/);
    assert.match(appcast, /github\.com\/garbledhamster\/putio-manager\/releases\/download\/v2\.2\.0/);
  }
  assert.equal((await catalog.inspectReleaseAssets(directory, version, 'published')).length, 21);
  assert.equal(await signing.verifySignedUpdates(directory, version, publicKey), true);
  await writeFile(path.join(directory, 'appcast-x64.xml'), 'altered fixture appcast');
  await assert.rejects(signing.verifySignedUpdates(directory, version, publicKey), /match|signature/i);
  bytes[0] ^= 1;
  assert.equal(verify(null, bytes, publicKey, Buffer.from(sig.trim(), 'base64')), false);
});
test('canonical signed metadata rejects duplicate names and noncanonical paths', () => {
  const asset = { name: 'fixture.zip', bytes: 1, sha256: 'a'.repeat(64) };
  assert.throws(() => signing.canonicalUpdateMetadata(version, [asset, asset]), /inventory/i);
  for (const altered of [{ name: '../fixture.zip' }, { name: '/fixture.zip' }, { name: 'fixture.zip?token=fixture' }, { bytes: 0 }, { bytes: 1.5 }, { sha256: 'invalid' }]) assert.throws(() => signing.canonicalUpdateMetadata(version, [{ ...asset, ...altered }]), /inventory/i);
});
test('signed Mac archive bindings are required, canonical and exclusive to Mac archives', () => {
  const asset = { name: `PutioManager-${version}-macos-x64-update.zip`, bytes: 1, sha256: 'a'.repeat(64) };
  for (const ed25519 of [undefined, '', 'invalid', Buffer.alloc(63).toString('base64'), Buffer.alloc(64).toString('base64').replace(/==$/, 'B=')]) assert.throws(() => signing.canonicalUpdateMetadata(version, [{ ...asset, ed25519 }]), /binding/i);
  const ed25519 = Buffer.alloc(64).toString('base64');
  assert.equal(JSON.parse(signing.canonicalUpdateMetadata(version, [{ ...asset, ed25519 }])).assets[0].ed25519, ed25519);
  assert.throws(() => signing.canonicalUpdateMetadata(version, [{ ...asset, name: 'fixture.zip', ed25519 }]), /binding/i);
});
test('publication verification rejects swapped architecture signatures even in a newly signed manifest', async t => {
  const directory = await fixture(t), pair = generateKeyPairSync('ed25519');
  const result = await signing.signUpdates(directory, version, pair.privateKey, pair.publicKey);
  const manifestFile = path.join(directory, result.manifest), manifest = JSON.parse(await readFile(manifestFile));
  const mac = manifest.assets.filter(asset => asset.name.endsWith('-update.zip'));
  assert.equal(mac.length, 2); assert.notEqual(mac[0].ed25519, mac[1].ed25519);
  [mac[0].ed25519, mac[1].ed25519] = [mac[1].ed25519, mac[0].ed25519];
  const changed = signing.canonicalUpdateMetadata(version, manifest.assets);
  await writeFile(manifestFile, changed);
  await writeFile(path.join(directory, result.signature), sign(null, changed, pair.privateKey).toString('base64') + '\n');
  await assert.rejects(signing.verifySignedUpdates(directory, version, pair.publicKey), /inventory/i);
});
test('signing refuses a different public key or an existing publication file', async t => {
  const directory = await fixture(t);
  const pair = generateKeyPairSync('ed25519'), different = generateKeyPairSync('ed25519');
  await assert.rejects(signing.signUpdates(directory, version, pair.privateKey, different.publicKey), /key/i);
  await signing.signUpdates(directory, version, pair.privateKey, pair.publicKey);
  await assert.rejects(signing.signUpdates(directory, version, pair.privateKey, pair.publicKey), /inventory|exist/i);
});
test('checksum CLI validates the whole stage and rejects changed archive bytes', async t => {
  const directory = await fixture(t), workspace = await mkdtemp(path.join(os.tmpdir(), 'putio-checksum-test-'));
  t.after(() => rm(workspace, { recursive: true, force: true }));
  await writeFile(path.join(workspace, 'package.json'), JSON.stringify({ version }));
  const script = fileURLToPath(new URL('../scripts/release-checksums.mjs', import.meta.url));
  const run = args => spawnSync(process.execPath, [script, ...args], { cwd: workspace, encoding: 'utf8' });
  assert.equal(run([directory, 'build']).status, 0);
  assert.equal(run(['--verify', directory, 'build']).status, 0);
  assert.equal((await readFile(path.join(directory, 'SHA256SUMS.txt'), 'utf8')).trim().split('\n').length, 17);
  await writeFile(path.join(directory, catalog.releaseAssetNames(version)[0]), 'changed generated bytes');
  assert.notEqual(run(['--verify', directory, 'build']).status, 0);
});
